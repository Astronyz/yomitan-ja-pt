"""Entry point for the public build. The full generator is maintained locally.
This wrapper intentionally requires --public so personal sources cannot be used."""
from pathlib import Path
import argparse, json, zipfile

def main():
    p=argparse.ArgumentParser(); p.add_argument('--public',action='store_true',required=True); p.parse_args()
    for path in Path('dictionaries').rglob('*.json'):
        json.loads(path.read_text(encoding='utf-8'))
    print('Public metadata validation passed; release assets are generated by the local public pipeline.')

if __name__ == '__main__': main()
